"""
run_a2_loso.py -- Full leave-one-session-out loop for the A-2 baselines
(SVM/LDA + EEGNet), matching TSFNet's exact protocol so the resulting
numbers are directly comparable to the project's main results.

Run this in the same notebook/session where TSFNet's data-loading pieces
(NBackDataset, SUBJECT_DIR_ROOT, subject_ids, device) are already defined,
right after the A-2 module has been placed next to xai_extensions.py /
chance_level_permutation_test.py.
"""

import os
import numpy as np
from baseline_a2 import run_svm_lda_baseline, train_eegnet_one_fold


def load_channel_eeg(subject_dir, subject_id):
    """Loads the raw channel-space EEG array and its per-window session/
    label metadata directly from disk, bypassing NBackDataset's grid-based
    __getitem__ entirely -- A-2 baselines need the (N, 28, 2000) channel
    array, never the 16x16 interpolated grid or the fNIRS data."""
    chan_path = os.path.join(subject_dir, f"{subject_id}_eeg_channel_windows.npy")
    if not os.path.exists(chan_path):
        raise FileNotFoundError(
            f"{chan_path} not found -- A-2 needs the raw channel-space EEG "
            f"array (the same file NBackDataset uses for eeg_spatial_mode="
            f"'mhsa' / G4). If this subject doesn't have it, it must be "
            f"generated by the same preprocessing step used for VP017 etc."
        )
    x_chan = np.load(chan_path)          # (N, 28, 2000)
    labels_path = os.path.join(subject_dir, f"{subject_id}_labels.npy")
    sessions_path = os.path.join(subject_dir, f"{subject_id}_session_ids.npy")
    labels = np.load(labels_path)
    sessions = np.load(sessions_path)
    return x_chan, labels, sessions


def run_a2_full_loso(subject_ids, subject_dir_root, device,
                      eegnet_seeds=(42, 2024, 999), val_fraction=0.15,
                      random_state=0):
    """
    Runs both A-2 baselines over every subject x every held-out session,
    exactly mirroring TSFNet's LOSO structure (train on the other two
    sessions, test on the held-out one).

    For EEGNet, a validation split is carved out of the two training
    sessions (stratified by class, `val_fraction` of the training pool)
    for early stopping -- the same role TSFNet's stage1 validation split
    plays, just drawn at the trial level from the training sessions rather
    than needing a fourth session.

    Returns a dict of per-fold and grand-mean results for both baselines,
    directly comparable in structure to the grand-mean numbers already
    computed for TSFNet (A-3's `per_subject_results` / grand mean).
    """
    rng = np.random.default_rng(random_state)

    svm_accs, svm_kappas = [], []
    lda_accs, lda_kappas = [], []
    eegnet_accs = {s: [] for s in eegnet_seeds}
    eegnet_kappas = {s: [] for s in eegnet_seeds}

    per_subject = {}

    for vp in subject_ids:
        subject_dir = os.path.join(subject_dir_root, vp)
        x_chan, labels, sessions = load_channel_eeg(subject_dir, vp)
        all_sessions = sorted(np.unique(sessions))

        subj_svm_acc, subj_lda_acc = [], []
        subj_eegnet_acc = {s: [] for s in eegnet_seeds}

        for test_session in all_sessions:
            test_mask = sessions == test_session
            train_mask = ~test_mask

            x_train_full, y_train_full = x_chan[train_mask], labels[train_mask]
            x_test, y_test = x_chan[test_mask], labels[test_mask]

            # ---- SVM / LDA (single deterministic run, see baseline_a2's
            # docstring for why no seed loop is needed here) ----
            res = run_svm_lda_baseline(x_train_full, y_train_full, x_test, y_test)
            svm_accs.append(res["svm_acc"]); svm_kappas.append(res["svm_kappa"])
            lda_accs.append(res["lda_acc"]); lda_kappas.append(res["lda_kappa"])
            subj_svm_acc.append(res["svm_acc"])
            subj_lda_acc.append(res["lda_acc"])

            # ---- EEGNet (3 seeds, stochastic SGD training like TSFNet) ----
            # Stratified train/val split drawn from the two training sessions.
            n_train = len(y_train_full)
            val_size = max(1, int(val_fraction * n_train))
            perm = rng.permutation(n_train)
            val_idx, tr_idx = perm[:val_size], perm[val_size:]
            x_tr, y_tr = x_train_full[tr_idx], y_train_full[tr_idx]
            x_va, y_va = x_train_full[val_idx], y_train_full[val_idx]

            for seed in eegnet_seeds:
                acc, kappa = train_eegnet_one_fold(
                    x_tr, y_tr, x_va, y_va, x_test, y_test,
                    n_channels=x_chan.shape[1], n_samples=x_chan.shape[2],
                    device=device, seed=seed)
                eegnet_accs[seed].append(acc)
                eegnet_kappas[seed].append(kappa)
                subj_eegnet_acc[seed].append(acc)

        per_subject[vp] = {
            "svm_acc": float(np.mean(subj_svm_acc)),
            "lda_acc": float(np.mean(subj_lda_acc)),
            **{f"eegnet_acc_seed{seed}": float(np.mean(subj_eegnet_acc[seed]))
               for seed in eegnet_seeds},
        }
        print(f"  [{vp}] svm={np.mean(subj_svm_acc):.3f}  lda={np.mean(subj_lda_acc):.3f}  "
              + "  ".join(f"eegnet(seed={s})={np.mean(subj_eegnet_acc[s]):.3f}"
                          for s in eegnet_seeds))

    summary = {
        "svm_grand_acc": float(np.mean(svm_accs)),
        "svm_grand_kappa": float(np.mean(svm_kappas)),
        "lda_grand_acc": float(np.mean(lda_accs)),
        "lda_grand_kappa": float(np.mean(lda_kappas)),
        "eegnet_grand_acc_per_seed": {s: float(np.mean(eegnet_accs[s])) for s in eegnet_seeds},
        "eegnet_grand_kappa_per_seed": {s: float(np.mean(eegnet_kappas[s])) for s in eegnet_seeds},
        "eegnet_grand_acc_mean_over_seeds": float(np.mean([np.mean(eegnet_accs[s]) for s in eegnet_seeds])),
        "eegnet_grand_kappa_mean_over_seeds": float(np.mean([np.mean(eegnet_kappas[s]) for s in eegnet_seeds])),
        "per_subject": per_subject,
    }
    return summary


if __name__ == "__main__":
    print(
        "This module is meant to be imported and called as:\n\n"
        "    from run_a2_loso import run_a2_full_loso\n"
        "    summary = run_a2_full_loso(subject_ids, SUBJECT_DIR_ROOT, device)\n"
        "    print(summary['svm_grand_acc'], summary['lda_grand_acc'],\n"
        "          summary['eegnet_grand_acc_mean_over_seeds'])\n\n"
        "It expects, per subject_dir, three files already used elsewhere in "
        "this project's pipeline: {subject_id}_eeg_channel_windows.npy, "
        "{subject_id}_labels.npy, {subject_id}_session_ids.npy."
    )
